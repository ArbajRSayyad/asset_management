-- This script is to create ASSET_ALLOCATION table
-- It stores list of assets held by an account
CREATE TABLE ASSET_ALLOCATION
(
    ASSET_ALLOC_ID GENERATED BY DEFAULT IDENTITY NUMBER PRIMARY KEY,
    ACCT_AST_MAP_ID NUMBER,
    ASSET_ID NUMBER NOT NULL,
    CONSTRAINT AST_ALLOC_UNQ_KEY (ACCT_AST_MAP_ID,ASSET_ID),
    CONSTRAINT ACCT_AST_FK FOREIGN KEY (ACCT_AST_MAP_ID) REFERENCES ACCOUNT_ASSET_MAP (ACCT_AST_MAP_ID)
);
/